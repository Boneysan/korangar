pub struct MonsterFacts {
    pub level: u16,
    pub element: &'static str,
    pub race: &'static str,
}

pub fn monster_facts(name: &str) -> Option<MonsterFacts> {
    let key = name.to_uppercase();
    CARDS.binary_search_by_key(&key.as_str(), |card| card.name).ok().map(|index| {
        let card = &CARDS[index];
        MonsterFacts { level: card.level, element: card.element, race: card.race }
    })
}
