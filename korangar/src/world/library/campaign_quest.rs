//! Seal Cascade hunting-contract requirements.
//!
//! The campaign's hunts are filled by handing in items, not by a kill counter,
//! so the quest log has to show which items a contract wants. Hercules never
//! sends that: `ZC_ADD_QUEST` and `ZC_ALL_QUEST_LIST` carry only the kill
//! objectives, and a converted contract has none. Rather than grow the wire
//! protocol for static data, the requirement list is generated straight from
//! the server's own master file and bundled here, the same way
//! `hercules_item_names.tsv` is.
//!
//! `Hercules/tools/gen-hunts.py --check` fails if this file has drifted from
//! `db/dm_hunt_db.json`, and `tools/check-campaign.sh` runs that check.

use hashbrown::HashMap;
use ragnarok_packets::ItemId;

/// Server-authored names, including story quests without item requirements.
/// Regenerate with `python3 tools/export_quest_names.py` after DB changes.
pub fn quest_display_name(quest_id: u32) -> Option<&'static str> {
    static NAMES: std::sync::OnceLock<HashMap<u32, &'static str>> = std::sync::OnceLock::new();
    NAMES
        .get_or_init(|| {
            include_str!("quest_names.tsv")
                .lines()
                .filter_map(|line| {
                    let (id, name) = line.split_once('\t')?;
                    Some((id.parse().ok()?, name))
                })
                .collect()
        })
        .get(&quest_id)
        .copied()
}

/// Generated by `Hercules/tools/gen-hunts.py`. Do not edit by hand.
const CAMPAIGN_QUESTS: &str = include_str!("campaign_quests.tsv");
const CAMPAIGN_LOCATIONS: &str = include_str!("campaign_quest_locations.tsv");
const OFFICIAL_LOCATIONS: &str = include_str!("quest_locations.tsv");

/// One item a contract asks for.
#[derive(Debug, Clone, Copy)]
pub struct QuestRequirement {
    pub item_id: ItemId,
    pub needed: u32,
}

/// A campaign hunting contract: its name and what it wants handed in.
#[derive(Debug, Clone)]
pub struct CampaignQuest {
    pub name: String,
    pub requirements: Vec<QuestRequirement>,
}

/// Where a journal quest sends the player (hunt zone and/or NPC).
#[derive(Debug, Clone)]
pub struct QuestLocation {
    pub hunt_zone: String,
    pub npc: String,
    pub map: String,
    pub x: u16,
    pub y: u16,
}

impl QuestLocation {
    pub fn journal_text(&self) -> String {
        let mut lines = Vec::new();
        if !self.hunt_zone.is_empty() {
            lines.push(format!("Hunt in: {}", self.hunt_zone.replace('/', ", ")));
        }
        if !self.npc.is_empty() {
            if self.map.is_empty() {
                lines.push(format!("Talk to: {}", self.npc));
            } else {
                lines.push(format!("Talk to: {} — {} ({}, {})", self.npc, self.map, self.x, self.y));
            }
        }
        lines.join("\n")
    }
}

/// Requirement lookup for campaign quest ids.
#[derive(Debug, Default, Clone)]
pub struct CampaignQuestTable {
    quests: HashMap<u32, CampaignQuest>,
    locations: HashMap<u32, QuestLocation>,
}

impl CampaignQuestTable {
    pub fn load() -> Self {
        let quests = parse_campaign_quests(CAMPAIGN_QUESTS);
        let mut locations = parse_official_locations(OFFICIAL_LOCATIONS);
        for (id, loc) in parse_quest_locations(CAMPAIGN_LOCATIONS) {
            locations.insert(id, loc);
        }

        #[cfg(feature = "debug")]
        {
            use korangar_debug::logging::print_debug;
            print_debug!("loaded campaign quest requirements: {} contracts", quests.len());
        }

        Self { quests, locations }
    }

    /// The contract for a quest id, or `None` for a story quest / any quest
    /// that is not part of the campaign's hunting layer.
    pub fn get(&self, quest_id: u32) -> Option<&CampaignQuest> {
        self.quests.get(&quest_id)
    }

    pub fn location(&self, quest_id: u32) -> Option<&QuestLocation> {
        self.locations.get(&quest_id)
    }
}

fn parse_campaign_quests(data: &str) -> HashMap<u32, CampaignQuest> {
    let mut quests = HashMap::new();

    for line in data.lines() {
        let line = line.trim_end();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }

        let mut fields = line.split('\t');
        let (Some(id), Some(name), Some(requirements)) = (fields.next(), fields.next(), fields.next()) else {
            continue;
        };
        let Ok(quest_id) = id.trim().parse::<u32>() else {
            continue;
        };

        let requirements = requirements
            .split(',')
            .filter_map(|pair| {
                let (item, count) = pair.split_once(':')?;
                Some(QuestRequirement {
                    item_id: ItemId(item.trim().parse().ok()?),
                    needed: count.trim().parse().ok()?,
                })
            })
            .collect::<Vec<_>>();

        // A contract with no parseable requirements would render as an empty
        // entry the player cannot act on; drop it rather than show a blank.
        if requirements.is_empty() {
            continue;
        }

        quests.insert(quest_id, CampaignQuest {
            name: name.trim().to_owned(),
            requirements,
        });
    }

    quests
}

fn parse_official_locations(data: &str) -> HashMap<u32, QuestLocation> {
    let mut locations = HashMap::new();
    for line in data.lines() {
        let line = line.trim_end();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let mut fields = line.split('\t');
        let (Some(id), Some(npc), Some(map), Some(x), Some(y)) =
            (fields.next(), fields.next(), fields.next(), fields.next(), fields.next())
        else {
            continue;
        };
        let hunt_zone = fields.next().unwrap_or("").trim().to_owned();
        let Ok(quest_id) = id.trim().parse::<u32>() else {
            continue;
        };
        if npc.trim().is_empty() && hunt_zone.is_empty() {
            continue;
        }
        locations.insert(quest_id, QuestLocation {
            hunt_zone,
            npc: npc.trim().to_owned(),
            map: map.trim().to_owned(),
            x: x.trim().parse().unwrap_or(0),
            y: y.trim().parse().unwrap_or(0),
        });
    }
    locations
}

fn parse_quest_locations(data: &str) -> HashMap<u32, QuestLocation> {
    let mut locations = HashMap::new();
    for line in data.lines() {
        let line = line.trim_end();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let mut fields = line.split('\t');
        let (Some(id), Some(_kind), Some(zone), Some(npc), Some(map), Some(x), Some(y)) = (
            fields.next(),
            fields.next(),
            fields.next(),
            fields.next(),
            fields.next(),
            fields.next(),
            fields.next(),
        ) else {
            continue;
        };
        let Ok(quest_id) = id.trim().parse::<u32>() else {
            continue;
        };
        locations.insert(quest_id, QuestLocation {
            hunt_zone: zone.trim().to_owned(),
            npc: npc.trim().to_owned(),
            map: map.trim().to_owned(),
            x: x.trim().parse().unwrap_or(0),
            y: y.trim().parse().unwrap_or(0),
        });
    }
    locations
}

#[cfg(test)]
mod tests {
    use super::{CampaignQuestTable, parse_campaign_quests};

    #[test]
    fn story_quests_have_names_without_becoming_item_contracts() {
        assert_eq!(super::quest_display_name(20001), Some("Omens at the Fountain"));
        assert!(CampaignQuestTable::load().get(20001).is_none());
        assert_eq!(super::quest_display_name(u32::MAX), None);
    }

    /// The bundled table has to actually parse, or every quest silently
    /// becomes a story quest with no requirements shown.
    #[test]
    fn the_bundled_table_parses() {
        let table = CampaignQuestTable::load();

        let cellar_vermin = table.get(20002).expect("20002 is a campaign hunting contract");
        assert_eq!(cellar_vermin.name, "Contract: Cellar Vermin");
        assert_eq!(cellar_vermin.requirements.len(), 3);
        assert!(cellar_vermin.requirements.iter().all(|requirement| requirement.needed > 0));
    }

    /// Story quests share the campaign's id range and must not be mistaken
    /// for contracts with an empty shopping list.
    #[test]
    fn a_story_quest_has_no_contract() {
        let table = CampaignQuestTable::load();
        assert!(table.get(20001).is_none());
    }

    #[test]
    fn comments_and_blank_lines_are_skipped() {
        let quests = parse_campaign_quests("# header\n\n20002\tName\t1016:7\n");
        assert_eq!(quests.len(), 1);
    }

    /// Every turn-in item has to resolve to a display name, or the quest log
    /// lists "NOTFOUND" and the player cannot tell what to collect. This is
    /// what the campaign's one custom item (the Sigil Ring, id 50001) does
    /// today: it is in the server's item db but not in the bundled name
    /// table, so it renders nameless.
    #[test]
    fn every_turn_in_item_has_a_display_name() {
        const HERCULES_ITEM_NAMES: &str = include_str!("hercules_item_names.tsv");

        let named: hashbrown::HashSet<u32> = HERCULES_ITEM_NAMES
            .lines()
            .filter_map(|line| line.split('\t').next()?.trim().parse().ok())
            .collect();

        let table = CampaignQuestTable::load();
        let nameless: Vec<u32> = table
            .quests
            .values()
            .flat_map(|quest| &quest.requirements)
            .map(|requirement| requirement.item_id.0)
            .filter(|item_id| !named.contains(item_id))
            .collect();

        assert!(nameless.is_empty(), "turn-in items with no display name: {nameless:?}");
    }

    /// A malformed row must not take the rest of the table down with it.
    #[test]
    fn a_malformed_row_is_dropped_not_fatal() {
        let quests = parse_campaign_quests("20002\tGood\t1016:7\nnope\tBad\tzzz\n20003\tAlso good\t940:10\n");
        assert_eq!(quests.len(), 2);
    }

    #[test]
    fn every_journal_hunt_has_a_hunt_zone_and_turn_in() {
        let table = CampaignQuestTable::load();
        let mut missing = Vec::new();
        for id in table.quests.keys() {
            match table.location(*id) {
                Some(loc) if !loc.hunt_zone.is_empty() && !loc.npc.is_empty() && !loc.map.is_empty() => {}
                other => missing.push((*id, other.map(|l| l.journal_text()))),
            }
        }
        assert!(missing.is_empty(), "hunts without location: {missing:?}");
        let rockers = table.location(20003).unwrap();
        assert!(rockers.hunt_zone.contains("prt_fild07"));
        assert!(rockers.npc.contains("Wynne"));
        let omens = table.location(20001).expect("story Omens at the Fountain");
        assert!(omens.npc.contains("Wynne"));
        assert_eq!(omens.map, "prontera");
        let acolyte = table.location(1001).expect("Job Change to Acolyte");
        assert!(!acolyte.npc.is_empty());
        assert!(!acolyte.map.is_empty());
        assert!(table.location(1000).is_some(), "Transcend / Valkyrie");
    }
}
