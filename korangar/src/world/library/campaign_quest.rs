//! Seal Cascade hunting-contract requirements.
//!
//! The campaign's hunts are filled by handing in items, not by a kill counter,
//! so the quest log has to show which items a contract wants. Hercules never
//! sends that: `ZC_ADD_QUEST` and `ZC_ALL_QUEST_LIST` carry only the kill
//! objectives, and a converted contract has none. Rather than grow the wire
//! protocol for static data, the requirement list is generated straight from
//! the server's own master file and bundled here, the same way
//! `hercules_item_names.tsv` is.
//!
//! `Hercules/tools/gen-hunts.py --check` fails if this file has drifted from
//! `db/dm_hunt_db.json`, and `tools/check-campaign.sh` runs that check.

use hashbrown::HashMap;
use ragnarok_packets::ItemId;

/// Generated by `Hercules/tools/gen-hunts.py`. Do not edit by hand.
const CAMPAIGN_QUESTS: &str = include_str!("campaign_quests.tsv");
/// Generated by `Hercules/tools/gen-hunts.py`: where each campaign quest's NPC
/// stands.
const QUEST_LOCATIONS: &str = include_str!("campaign_quest_locations.tsv");
/// Generated by `Hercules/tools/gen-hunts.py`: the player-facing steps of each
/// contract.
const HUNT_GUIDANCE: &str = include_str!("hunt_guidance.tsv");

/// One item a contract asks for.
#[derive(Debug, Clone, Copy)]
pub struct QuestRequirement {
    pub item_id: ItemId,
    pub needed: u32,
}

/// A campaign hunting contract: its name and what it wants handed in.
#[derive(Debug, Clone)]
pub struct CampaignQuest {
    pub name: String,
    pub requirements: Vec<QuestRequirement>,
}

/// Where a campaign quest's NPC stands, read from the NPC script's own header.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct QuestLocation {
    /// A hunting contract's turn-in NPC, or a story quest's marker NPC.
    pub is_turn_in: bool,
    pub npc: String,
    pub map_name: String,
    pub x: u16,
    pub y: u16,
}

/// The player-facing outline of a hunting contract.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct QuestGuidance {
    pub npc: String,
    /// Where the items are found: a place name, or the raw map codes when none
    /// is on record.
    pub area: String,
    pub steps: Vec<String>,
}

/// Requirement, location and guidance lookup for campaign quest ids.
#[derive(Debug, Default, Clone)]
pub struct CampaignQuestTable {
    quests: HashMap<u32, CampaignQuest>,
    locations: HashMap<u32, QuestLocation>,
    guidance: HashMap<u32, QuestGuidance>,
}

impl CampaignQuestTable {
    pub fn load() -> Self {
        let quests = parse_campaign_quests(CAMPAIGN_QUESTS);
        let locations = parse_quest_locations(QUEST_LOCATIONS);
        let guidance = parse_hunt_guidance(HUNT_GUIDANCE);

        #[cfg(feature = "debug")]
        {
            use korangar_debug::logging::print_debug;
            print_debug!(
                "loaded campaign quest data: {} contracts, {} locations, {} guidance rows",
                quests.len(),
                locations.len(),
                guidance.len()
            );
        }

        Self {
            quests,
            locations,
            guidance,
        }
    }

    /// The contract for a quest id, or `None` for a story quest / any quest
    /// that is not part of the campaign's hunting layer.
    pub fn get(&self, quest_id: u32) -> Option<&CampaignQuest> {
        self.quests.get(&quest_id)
    }

    /// The NPC to go to for a campaign quest, if the scripts name one.
    pub fn location(&self, quest_id: u32) -> Option<&QuestLocation> {
        self.locations.get(&quest_id)
    }

    /// The steps of a hunting contract, if it has any.
    pub fn guidance(&self, quest_id: u32) -> Option<&QuestGuidance> {
        self.guidance.get(&quest_id)
    }
}

fn parse_quest_locations(data: &str) -> HashMap<u32, QuestLocation> {
    let mut locations = HashMap::new();

    for line in data.lines() {
        let line = line.trim_end();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }

        // quest_id, kind, hunt_zone, npc, map, x, y
        let fields: Vec<&str> = line.split('\t').collect();
        let [id, kind, _zone, npc, map_name, x, y] = fields[..] else {
            continue;
        };
        let (Ok(quest_id), Ok(x), Ok(y)) = (id.trim().parse::<u32>(), x.trim().parse::<u16>(), y.trim().parse::<u16>()) else {
            continue;
        };
        // A row without a map or an NPC gives the player nowhere to go.
        if npc.trim().is_empty() || map_name.trim().is_empty() {
            continue;
        }

        locations.insert(quest_id, QuestLocation {
            is_turn_in: kind.trim() == "hunt",
            npc: npc.trim().to_owned(),
            map_name: map_name.trim().to_owned(),
            x,
            y,
        });
    }

    locations
}

fn parse_hunt_guidance(data: &str) -> HashMap<u32, QuestGuidance> {
    let mut guidance = HashMap::new();

    for line in data.lines() {
        let line = line.trim_end();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }

        // quest_id, npc, area, steps ('|'-separated)
        let mut fields = line.split('\t');
        let (Some(id), Some(npc), Some(area), Some(steps)) = (fields.next(), fields.next(), fields.next(), fields.next()) else {
            continue;
        };
        let Ok(quest_id) = id.trim().parse::<u32>() else {
            continue;
        };
        let steps: Vec<String> = steps
            .split('|')
            .map(str::trim)
            .filter(|step| !step.is_empty())
            .map(str::to_owned)
            .collect();
        if steps.is_empty() {
            continue;
        }

        guidance.insert(quest_id, QuestGuidance {
            npc: npc.trim().to_owned(),
            area: area.trim().to_owned(),
            steps,
        });
    }

    guidance
}

fn parse_campaign_quests(data: &str) -> HashMap<u32, CampaignQuest> {
    let mut quests = HashMap::new();

    for line in data.lines() {
        let line = line.trim_end();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }

        let mut fields = line.split('\t');
        let (Some(id), Some(name), Some(requirements)) = (fields.next(), fields.next(), fields.next()) else {
            continue;
        };
        let Ok(quest_id) = id.trim().parse::<u32>() else {
            continue;
        };

        let requirements = requirements
            .split(',')
            .filter_map(|pair| {
                let (item, count) = pair.split_once(':')?;
                Some(QuestRequirement {
                    item_id: ItemId(item.trim().parse().ok()?),
                    needed: count.trim().parse().ok()?,
                })
            })
            .collect::<Vec<_>>();

        // A contract with no parseable requirements would render as an empty
        // entry the player cannot act on; drop it rather than show a blank.
        if requirements.is_empty() {
            continue;
        }

        quests.insert(quest_id, CampaignQuest {
            name: name.trim().to_owned(),
            requirements,
        });
    }

    quests
}

#[cfg(test)]
mod tests {
    use super::{CampaignQuestTable, parse_campaign_quests, parse_hunt_guidance, parse_quest_locations};

    /// The bundled table has to actually parse, or every quest silently
    /// becomes a story quest with no requirements shown.
    #[test]
    fn the_bundled_table_parses() {
        let table = CampaignQuestTable::load();

        let cellar_vermin = table.get(20002).expect("20002 is a campaign hunting contract");
        assert_eq!(cellar_vermin.name, "Contract: Cellar Vermin");
        assert_eq!(cellar_vermin.requirements.len(), 3);
        assert!(cellar_vermin.requirements.iter().all(|requirement| requirement.needed > 0));
    }

    /// Story quests share the campaign's id range and must not be mistaken
    /// for contracts with an empty shopping list.
    #[test]
    fn a_story_quest_has_no_contract() {
        let table = CampaignQuestTable::load();
        assert!(table.get(20001).is_none());
    }

    #[test]
    fn comments_and_blank_lines_are_skipped() {
        let quests = parse_campaign_quests("# header\n\n20002\tName\t1016:7\n");
        assert_eq!(quests.len(), 1);
    }

    /// Every turn-in item has to resolve to a display name, or the quest log
    /// lists "NOTFOUND" and the player cannot tell what to collect. This is
    /// what the campaign's one custom item (the Sigil Ring, id 50001) does
    /// today: it is in the server's item db but not in the bundled name
    /// table, so it renders nameless.
    #[test]
    fn every_turn_in_item_has_a_display_name() {
        const HERCULES_ITEM_NAMES: &str = include_str!("hercules_item_names.tsv");

        let named: hashbrown::HashSet<u32> = HERCULES_ITEM_NAMES
            .lines()
            .filter_map(|line| line.split('\t').next()?.trim().parse().ok())
            .collect();

        let table = CampaignQuestTable::load();
        let nameless: Vec<u32> = table
            .quests
            .values()
            .flat_map(|quest| &quest.requirements)
            .map(|requirement| requirement.item_id.0)
            .filter(|item_id| !named.contains(item_id))
            .collect();

        assert!(nameless.is_empty(), "turn-in items with no display name: {nameless:?}");
    }

    /// A malformed row must not take the rest of the table down with it.
    #[test]
    fn a_malformed_row_is_dropped_not_fatal() {
        let quests = parse_campaign_quests("20002\tGood\t1016:7\nnope\tBad\tzzz\n20003\tAlso good\t940:10\n");
        assert_eq!(quests.len(), 2);
    }

    /// The turn-in NPC comes from the script that collects the contract, not
    /// from a per-arc guess. Einbroch's hunts are the case that proved it:
    /// 20113 is handed to Greta Holm at 171,226 and 20115 to the Medical
    /// Station at 166,222, neither of which is where the old hub table sent
    /// the player.
    #[test]
    fn a_contract_routes_to_the_npc_that_collects_it() {
        let table = CampaignQuestTable::load();

        let wynne = table.location(20002).expect("20002 has a turn-in NPC");
        assert!(wynne.is_turn_in);
        assert_eq!(
            (wynne.npc.as_str(), wynne.map_name.as_str(), wynne.x, wynne.y),
            ("Quartermaster Wynne", "prontera", 156, 191)
        );

        let greta = table.location(20113).expect("20113 has a turn-in NPC");
        assert_eq!(
            (greta.npc.as_str(), greta.map_name.as_str(), greta.x, greta.y),
            ("Greta Holm", "einbroch", 171, 226)
        );
        let station = table.location(20115).expect("20115 has a turn-in NPC");
        assert_eq!((station.npc.as_str(), station.x, station.y), ("Medical Station", 166, 222));
    }

    /// A contract nobody collects has nowhere to send the player; it must have
    /// no location rather than a guessed one. 20232 is the finale's retired
    /// hunt.
    #[test]
    fn an_uncollected_contract_has_no_location() {
        let table = CampaignQuestTable::load();
        assert!(table.location(20232).is_none());
        assert!(table.guidance(20232).is_none());
    }

    /// A story quest is marked on its NPC; it is not a turn-in.
    #[test]
    fn a_story_quest_location_is_a_contact_not_a_turn_in() {
        let table = CampaignQuestTable::load();
        let story = table.location(20001).expect("20001 is marked on an NPC");
        assert!(!story.is_turn_in);
    }

    /// Every contract the quest log can list has to be actionable: a turn-in
    /// cell and an outline. A missing row is a quest the player cannot find.
    #[test]
    fn every_contract_has_a_location_and_guidance() {
        let table = CampaignQuestTable::load();
        let mut missing = Vec::new();
        for id in table.quests.keys() {
            let located = table.location(*id).is_some_and(|location| location.is_turn_in);
            let guided = table.guidance(*id).is_some_and(|guidance| guidance.steps.len() >= 2);
            if !located || !guided {
                missing.push(*id);
            }
        }
        missing.sort_unstable();
        // 20232 is the one contract no NPC collects; the generator skips it.
        assert!(
            missing.is_empty() || missing == [20232],
            "contracts without a turn-in cell or outline: {missing:?}"
        );
    }

    /// A route button for a map the navigation graph does not know would do
    /// nothing, so the quest log shows plain text for those. This pins the
    /// known set: a new unroutable turn-in map fails here, and so does fixing
    /// the graph, which is the cue to delete the exception.
    #[test]
    fn every_turn_in_map_is_routable_except_the_known_gap() {
        // The Varmundt interior (arc 17) is not in `navigation_graph.json`.
        const KNOWN_UNROUTABLE: [(u32, &str); 2] = [(20212, "ba_in01"), (20213, "ba_in01")];

        let table = CampaignQuestTable::load();
        let graph = crate::world::navigation_graph();
        let mut unroutable: Vec<(u32, String)> = table
            .quests
            .keys()
            .filter_map(|id| table.location(*id).map(|location| (*id, location.map_name.clone())))
            .filter(|(_, map)| !graph.maps.iter().any(|known| known.eq_ignore_ascii_case(map)))
            .collect();
        unroutable.sort();
        let expected: Vec<(u32, String)> = KNOWN_UNROUTABLE.iter().map(|(id, map)| (*id, (*map).to_owned())).collect();
        assert_eq!(unroutable, expected, "turn-in maps the navigation graph does not know changed");
    }

    #[test]
    fn a_location_row_without_an_npc_or_map_is_dropped() {
        let locations = parse_quest_locations(
            "20002\thunt\tz\tWynne\tprontera\t156\t191\n20003\thunt\tz\t\tprontera\t1\t1\n20004\thunt\tz\tNpc\t\t1\t1\nbad\thunt\tz\tN\tm\\
             \
             t1\t1\n",
        );
        assert_eq!(locations.len(), 1);
        assert_eq!(locations[&20002].x, 156);
    }

    #[test]
    fn guidance_steps_split_on_the_bar_and_empty_outlines_are_dropped() {
        let guidance = parse_hunt_guidance("# schema=1\n20002\tWynne\tCulverts\tBring a|Turn in to Wynne\n20003\tWynne\tField\t\n");
        assert_eq!(guidance.len(), 1);
        assert_eq!(guidance[&20002].steps, ["Bring a", "Turn in to Wynne"]);
        assert_eq!(guidance[&20002].area, "Culverts");
    }
}
